def run_case(name, rows, direction, legs, expected):
    print(f"\n{'='*60}\nSCENARIO: {name}\n{'='*60}")
    candles = make_candles(rows)
    b = StructureBuilder()
    for c in candles:
        b.process(c)
    ok = True
    if b.direction.value.upper() != direction:
        print(f"  FAIL direction: expected={direction} got={b.direction}"); ok = False
    if b.confirmed_legs != legs:
        print(f"  FAIL confirmed_legs: expected={legs} got={b.confirmed_legs}"); ok = False
    owned = {c.index for s in b.segments for c in s.candles} | {c.index for c in b.candidate}
    lost = [c.time for c in candles if c.index not in owned]
    if lost:
        print(f"  FAIL lost candles: {lost}"); ok = False
    got = [(p["kind"], p["n"], p["start"], p["end"], p["confirmed"]) for p in b.points()]
    for i, exp in enumerate(expected):
        g = got[i] if i < len(got) else None
        mark = "ok  " if g is not None and g[:2] == exp[:2] and abs(g[2]-exp[2]) < 0.1 \
            and abs(g[3]-exp[3]) < 0.1 and g[4] == exp[4] else "FAIL"
        if mark == "FAIL":
            ok = False
        print(f"  {mark} {exp[0]:4} {exp[1]}: expected {exp[2]:.0f}-{exp[3]:.0f}"
              f"{'' if exp[4] else ' (forming)'}  got {g[2]:.0f}-{g[3]:.0f}" if g and g[3] is not None
              else f"  {mark} {exp[0]:4} {exp[1]}: expected {exp[2]:.0f}-{exp[3]:.0f}  got {g}")
    print("\n  PASS" if ok else "\n  FAIL")
    return ok


